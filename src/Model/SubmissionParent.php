    public function needsAnnex(string $annex): bool
    {
        return match ($annex) {
            'abroad' => $this->ResidenceGermany === 'no',
            'citizenship' => (bool) $this->Extended && $this->Citizenship === 'other',
            'income' => (bool) $this->AfterEmployed || (bool) $this->AfterProfit,
            'employer' => (bool) $this->AfterEmployed && (bool) $this->EmployerCertificate,
            default => false,
        };
    }

