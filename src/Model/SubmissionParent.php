    /**
     * Word-wrapped part of a value printed over several single-line PDF fields (2.c Straße: Str_1 / Str_2).
     * Long words are cut hard; the last line takes the rest (the form field is limited to two lines' worth).
     */
    public function LineOf(string $fieldName, string $line): string
    {
        $lines = self::wrapLines($this->text($fieldName), max(10, (int) $this->config()->get('line_width')));
        $index = max(1, (int) $line) - 1;
        if ($index === 1) {
            return trim(implode(' ', array_slice($lines, 1)));
        }

        return $lines[$index] ?? '';
    }

    /**
     * @return array<int, string>
     */
    public static function wrapLines(string $value, int $width): array
    {
        if ($value === '') {
            return [];
        }

        return explode("\n", wordwrap($value, $width, "\n", true));
    }

