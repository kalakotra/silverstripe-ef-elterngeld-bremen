    /**
     * @param array<string, mixed> $data step data without the P1 / P2 prefix
     */
    public static function fromStepData(int $number, array $data, bool $extended): self
    {
        $record = self::create();
        $db = (array) self::config()->get('db');

        foreach ($data as $field => $value) {
            if (array_key_exists($field, $db) && !in_array($field, ['Number', 'Extended'], true)) {
                $record->setField($field, $value);
            }
        }

        $record->Number = $number;
        $record->Extended = $extended;

        return $record;
    }

    /**
     * Rules of this column: shared rules + the rules of fields that exist in column 2E only.
     *
     * @return array<int, array<int, mixed>>
     */
    public static function rulesFor(int $number): array
    {
        $roleRules = (array) (self::config()->get('role_field_conditions')['p' . $number] ?? []);

        return array_merge((array) self::config()->get('field_conditions'), $roleRules);
    }

