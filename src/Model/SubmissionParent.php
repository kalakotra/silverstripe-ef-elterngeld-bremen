        return $this->CitizenshipType === $type ? $this->text($fieldName) : '';
    }

    /**
     * Postal address for the Arbeitgeberbescheinigung: own German address, the address of parent 1 when living
     * together (2.c), or the foreign address (Anlage Wohnsitz im Ausland).
     */
    private function addressPart(string $key): string
    {
        $source = $this;
        if ((int) $this->Number === 2 && $this->SameAddress === 'yes') {
            $source = $this->parentSubmission()?->parentRecord(1) ?? $this;
        }

        if ($source->ResidenceGermany === 'no') {
            return match ($key) {
                'AddressStreet' => $source->text('AbroadStreet'),
                'AddressHouseNumber' => $source->text('AbroadHouseNumber'),
                'AddressPostalCode' => $source->text('AbroadPostalCode'),
                'AddressCity' => trim($source->text('AbroadCity') . ', ' . $source->text('AbroadCountry'), ' ,'),
                'AddressExtra' => $source->text('AbroadAddressExtra'),
                default => '',
            };
        }

        return match ($key) {
            'AddressStreet' => $source->text('Street'),
            'AddressHouseNumber' => $source->text('HouseNumber'),
            'AddressPostalCode' => $source->text('PostalCode'),
            'AddressCity' => $source->text('City'),
            'AddressExtra' => $source->text('AddressExtra'),
            default => '',
        };
    }

    protected function parentSubmission(): ?Submission
    {
        $parent = $this->Submission();

        return $parent && $parent->exists() ? $parent : null;
    }

    public function text(string $fieldName): string
    {
        return trim((string) preg_replace('/\s+/', ' ', (string) ($this->getField($fieldName) ?? '')));
    }
