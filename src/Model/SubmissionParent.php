    /**
     * Annex header values: Person* (this parent), Address* (postal address of this parent), Child* / SignatureDate
     * (main submission).
     */
    public function Document(string $fieldName, string $key): string
    {
        if (str_starts_with($key, 'Person')) {
            return $key === 'PersonBirthDate' ? (string) $this->DateFormating('BirthDate') : $this->text(substr($key, 6));
        }

        if (str_starts_with($key, 'Address')) {
            return $this->addressPart($key);
        }

        $parent = $this->parentSubmission();

        return $parent ? $parent->textFor($key) : '';
    }

