    /**
     * @return array<int, SubmissionParent> indexed by Number (1 = "Sie", 2 = anderer Elternteil)
     */
    public function parentRecords(): array
    {
        $records = [];
        $list = $this->Parents();
        if ($list instanceof DataList) {
            foreach ($list as $record) {
                $records[(int) $record->Number] = $record;
            }
        }
        ksort($records);

        return $records;
    }

